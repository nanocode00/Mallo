#!/usr/bin/env python3
"""Generate web/runtime-config.js from environment or .env file."""

from __future__ import annotations

import os
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUTPUT_FILE = ROOT / "web" / "runtime-config.js"
ENV_FILE = ROOT / ".env"


def parse_env_file(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    env_vars = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip().strip("'\"")
        env_vars[key] = value
    return env_vars


def normalize_api_base_url(domain_or_url: str | None) -> str:
    if not domain_or_url or not domain_or_url.strip():
        return ""
    val = domain_or_url.strip()
    if val.startswith("http://") or val.startswith("https://"):
        return val.rstrip("/")
    return f"https://{val}".rstrip("/")


def generate_runtime_config(domain: str | None = None) -> str:
    if domain is None:
        # 1. Look in process environment
        domain = os.environ.get("CLOUDFLARE_DOMAIN")
        if not domain:
            # 2. Look in .env file
            env_vars = parse_env_file(ENV_FILE)
            domain = env_vars.get("CLOUDFLARE_DOMAIN")

    api_base_url = normalize_api_base_url(domain)

    content = f"""/*
 * Generated by scripts/runtime/generate_runtime_config.py - DO NOT EDIT DIRECTLY.
 * Public runtime configuration for Mallo web client.
 * Secret tokens or keys must NEVER be placed in this file.
 */
(() => {{
  const localHosts = new Set(["localhost", "127.0.0.1", "::1"]);
  const configuredBaseUrl = {repr(api_base_url)};

  let resolvedBaseUrl = window.MALLO_RUNTIME_CONFIG?.apiBaseUrl ?? window.MALLO_API_BASE_URL;

  if (resolvedBaseUrl === undefined) {{
    if (localHosts.has(window.location.hostname)) {{
      resolvedBaseUrl = "";
    }} else {{
      resolvedBaseUrl = configuredBaseUrl;
    }}
  }}

  window.MALLO_RUNTIME_CONFIG = Object.freeze({{
    apiBaseUrl: resolvedBaseUrl,
  }});

  // Backward compatibility with legacy window.MALLO_API_BASE_URL
  window.MALLO_API_BASE_URL = window.MALLO_RUNTIME_CONFIG.apiBaseUrl;
}})();
"""
    return content


def write_runtime_config(target_path: Path = OUTPUT_FILE, domain: str | None = None) -> Path:
    content = generate_runtime_config(domain)
    target_path.parent.mkdir(parents=True, exist_ok=True)
    target_path.write_text(content, encoding="utf-8")
    return target_path


def main() -> int:
    path = write_runtime_config()
    domain = os.environ.get("CLOUDFLARE_DOMAIN") or parse_env_file(ENV_FILE).get("CLOUDFLARE_DOMAIN") or "(none, localhost fallback)"
    print(f"[runtime-config] Generated {path.relative_to(ROOT)} (CLOUDFLARE_DOMAIN={domain})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
