#!/usr/bin/env node
/**
 * Generate web/runtime-config.js from environment or .env file (Node.js version).
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "../..");
const outputFile = path.join(root, "web/runtime-config.js");
const envFile = path.join(root, ".env");

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const vars = {};
  const content = fs.readFileSync(filePath, "utf-8");
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#") || !trimmed.includes("=")) continue;
    const [key, ...rest] = trimmed.split("=");
    const val = rest.join("=").trim().replace(/^['"]|['"]$/g, "");
    vars[key.trim()] = val;
  }
  return vars;
}

function normalizeApiBaseUrl(domainOrUrl) {
  if (!domainOrUrl || !domainOrUrl.trim()) return "";
  const val = domainOrUrl.trim();
  if (val.startsWith("http://") || val.startsWith("https://")) {
    return val.replace(/\/+$/, "");
  }
  return `https://${val}`.replace(/\/+$/, "");
}

function main() {
  let domain = process.env.CLOUDFLARE_DOMAIN;
  if (!domain) {
    const envVars = parseEnvFile(envFile);
    domain = envVars.CLOUDFLARE_DOMAIN;
  }

  const apiBaseUrl = normalizeApiBaseUrl(domain);

  const content = `/*
 * Generated by scripts/runtime/generate_runtime_config.js - DO NOT EDIT DIRECTLY.
 * Public runtime configuration for Mallo web client.
 * Secret tokens or keys must NEVER be placed in this file.
 */
(() => {
  const localHosts = new Set(["localhost", "127.0.0.1", "::1"]);
  const configuredBaseUrl = ${JSON.stringify(apiBaseUrl)};

  let resolvedBaseUrl = window.MALLO_RUNTIME_CONFIG?.apiBaseUrl ?? window.MALLO_API_BASE_URL;

  if (resolvedBaseUrl === undefined) {
    if (localHosts.has(window.location.hostname)) {
      resolvedBaseUrl = "";
    } else {
      resolvedBaseUrl = configuredBaseUrl;
    }
  }

  window.MALLO_RUNTIME_CONFIG = Object.freeze({
    apiBaseUrl: resolvedBaseUrl,
  });

  // Backward compatibility with legacy window.MALLO_API_BASE_URL
  window.MALLO_API_BASE_URL = window.MALLO_RUNTIME_CONFIG.apiBaseUrl;
})();
`;

  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, content, "utf-8");
  console.log(`[runtime-config] Generated ${path.relative(root, outputFile)} (CLOUDFLARE_DOMAIN=${domain || "(none, localhost fallback)"})`);
}

main();
